using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Testing;
using Xunit;

namespace FEx.Analyzers.Tests;

/// <summary>Guards that need more than one source file, an executable, or code that does not compile.</summary>
public class AnalyzerGuardTests
{
    private const string Banner = "// <auto-generated/>\n";

    private static Task Silent<TAnalyzer>(string source, string[]? otherFiles = null, OutputKind outputKind = OutputKind.DynamicallyLinkedLibrary, CompilerDiagnostics compilerDiagnostics = CompilerDiagnostics.Errors, string? editorConfig = null)
        where TAnalyzer : DiagnosticAnalyzer, new() =>
        AnalyzerTestHelper.VerifyAsync<TAnalyzer>(source, outputKind, otherFiles: otherFiles, compilerDiagnostics: compilerDiagnostics, editorConfig: editorConfig);

    // The editorconfig option wins over what the file looks like.
    [Fact]
    public Task FEX0039_never_reports_in_a_file_the_editorconfig_marks_generated() =>
        Silent<RedundantOverloadGlobalAnalyzer>(
            "public class R { public void M(int a) { M(a, 0); } public void M(int a, int b = 0) { System.Console.Write(a + b); } }",
            editorConfig: "root = true\n[*.cs]\ngenerated_code = true\n");

    // The method-group use sits in generated code (Razor binds handlers that way); the sibling the fix would drop is what it binds.
    [Fact]
    public Task FEX0039_method_group_in_generated_code_counts() =>
        Silent<RedundantOverloadGlobalAnalyzer>(
            "public class R { public void M(int a) { M(a, 0); } public void M(int a, int b = 0) { System.Console.Write(a + b); } }",
            [Banner + "public class Use { public System.Action<int> F(R r) => r.M; }"]);

    [Fact]
    public Task FEX0040_method_group_in_generated_code_counts() =>
        Silent<RedundantOverloadLocalAnalyzer>(
            "public partial class R { private void M(int a) { M(a, 0); } private void M(int a, int b = 0) { System.Console.Write(a + b); } }",
            [Banner + "public partial class R { public System.Action<int> F() => M; }"]);

    [Fact]
    public Task FEX0039_never_reports_in_generated_code() =>
        Silent<RedundantOverloadGlobalAnalyzer>(Banner + "public class R { public void M(int a) { M(a, 0); } public void M(int a, int b = 0) { System.Console.Write(a + b); } }");

    [Fact]
    public Task FEX0049_use_in_generated_code_counts() =>
        Silent<UnusedMethodReturnValueLocalAnalyzer>(
            "public partial class U { private int Compute() => 42; public void M() { Compute(); } }",
            [Banner + "public partial class U { public void G() { var x = Compute(); System.Console.Write(x); } }"]);

    [Fact]
    public Task FEX0049_never_reports_in_generated_code() =>
        Silent<UnusedMethodReturnValueLocalAnalyzer>(Banner + "public class U { private int Compute() => 42; public void M() { Compute(); } }");

    [Fact]
    public Task FEX0051_write_in_generated_code_counts() =>
        Silent<ConvertToConstantLocalAnalyzer>(
            "public partial class K { private int _mode = 1; public int G() => _mode; }",
            [Banner + "public partial class K { public void S() { _mode = 2; } }"]);

    [Fact]
    public Task FEX0051_never_reports_in_generated_code() =>
        Silent<ConvertToConstantLocalAnalyzer>(Banner + "public class K { private int _mode = 1; public int G() => _mode; public int M() { int size = 5; return size; } }");

    [Fact]
    public Task FEX0037_top_level_function_parameter_does_not_hide_a_static_field_of_Program() =>
        Silent<ParameterHidesMemberAnalyzer>(
            """
            F(1);
            void F(int count) { System.Console.Write(count); }
            partial class Program { private static int count; }
            """,
            outputKind: OutputKind.ConsoleApplication);

    [Fact]
    public Task FEX0038_top_level_local_does_not_hide_a_static_field_of_Program() =>
        Silent<LocalVariableHidesMemberAnalyzer>(
            """
            var count = 1;
            System.Console.Write(count);
            partial class Program { private static int count; }
            """,
            outputKind: OutputKind.ConsoleApplication);

    // Editors run analyzers over code that does not bind yet; an exception there shows as an AD0001 banner while the user types.
    [Fact]
    public Task FEX0037_lambda_parameter_in_an_assembly_attribute_does_not_crash() =>
        Silent<ParameterHidesMemberAnalyzer>(
            """
            using System;
            [assembly: A(x => x)]
            public class A : Attribute { public A(object o) { } }
            """,
            compilerDiagnostics: CompilerDiagnostics.None);

    [Fact]
    public Task FEX0038_pattern_variable_in_an_assembly_attribute_does_not_crash() =>
        Silent<LocalVariableHidesMemberAnalyzer>(
            """
            using System;
            [assembly: A(1 is int y)]
            public class A : Attribute { public A(object o) { } }
            """,
            compilerDiagnostics: CompilerDiagnostics.None);

    [Fact]
    public Task FEX0044_partial_property_accessor_without_implementation_does_not_crash() =>
        Silent<PartialMethodWithSinglePartAnalyzer>("public partial class C { public partial int Prop { get; } }", compilerDiagnostics: CompilerDiagnostics.None);

    // The attribute is how a source generator or a designer tags a type in a file whose name and header give nothing away.
    [Fact]
    public Task FEX0039_never_reports_in_a_type_tagged_GeneratedCode() =>
        Silent<RedundantOverloadGlobalAnalyzer>("[System.CodeDom.Compiler.GeneratedCode(\"tool\", \"1\")] public class R { public void M(int a) { M(a, 0); } public void M(int a, int b = 0) { System.Console.Write(a + b); } }");

    [Fact]
    public Task FEX0049_never_reports_in_a_type_tagged_CompilerGenerated() =>
        Silent<UnusedMethodReturnValueLocalAnalyzer>("[System.Runtime.CompilerServices.CompilerGenerated] public class U { private int Compute() => 42; public void M() { Compute(); } }");

    [Fact]
    public Task FEX0051_never_reports_in_a_nested_type_of_a_tagged_type() =>
        Silent<ConvertToConstantLocalAnalyzer>("[System.CodeDom.Compiler.GeneratedCode(\"tool\", \"1\")] public class K { private class N { private int _mode = 1; public int G() => _mode; } }");

    [Fact]
    public Task FEX0054_never_reports_in_generated_code() =>
        Silent<RedundantEmptyObjectCreationArgumentListAnalyzer>(Banner + "public class R { public int A; public R M() => new R() { A = 1 }; }");

    [Fact]
    public Task FEX0055_never_reports_in_generated_code() =>
        Silent<RedundantEmptyObjectOrCollectionInitializerAnalyzer>(Banner + "public class R { public R M() => new R { }; }");

    [Fact]
    public Task FEX0056_never_reports_in_generated_code() =>
        Silent<InvokeAsExtensionMemberAnalyzer>(Banner + "using System.Collections.Generic; using System.Linq; public class R { public int M(List<int> l) => Enumerable.Count(l); }");

    [Fact]
    public Task FEX0057_never_reports_in_generated_code() =>
        Silent<ParameterOnlyUsedForPreconditionCheckGlobalAnalyzer>(Banner + "public class R { public void M(string s) { System.ArgumentNullException.ThrowIfNull(s); System.Console.Write(1); } }");

    [Fact]
    public Task FEX0058_never_reports_in_generated_code() =>
        Silent<ParameterOnlyUsedForPreconditionCheckLocalAnalyzer>(Banner + "public class R { private void M(string s) { System.ArgumentNullException.ThrowIfNull(s); System.Console.Write(1); } }");

    [Fact]
    public Task FEX0057_method_group_in_generated_code_counts() =>
        Silent<ParameterOnlyUsedForPreconditionCheckGlobalAnalyzer>(
            "public partial class R { public void M(string s) { System.ArgumentNullException.ThrowIfNull(s); System.Console.Write(1); } }",
            [Banner + "public partial class R { public System.Action<string> F() => M; }"]);

    [Fact]
    public Task FEX0058_method_group_in_generated_code_counts() =>
        Silent<ParameterOnlyUsedForPreconditionCheckLocalAnalyzer>(
            "public partial class R { private void M(string s) { System.ArgumentNullException.ThrowIfNull(s); System.Console.Write(1); } }",
            [Banner + "public partial class R { public System.Action<string> F() => M; }"]);

    [Fact]
    public Task FEX0057_never_reports_in_a_type_tagged_GeneratedCode() =>
        Silent<ParameterOnlyUsedForPreconditionCheckGlobalAnalyzer>("[System.CodeDom.Compiler.GeneratedCode(\"tool\", \"1\")] public class R { public void M(string s) { System.ArgumentNullException.ThrowIfNull(s); System.Console.Write(1); } }");

    [Fact]
    public Task FEX0058_never_reports_in_a_type_tagged_CompilerGenerated() =>
        Silent<ParameterOnlyUsedForPreconditionCheckLocalAnalyzer>("[System.Runtime.CompilerServices.CompilerGenerated] public class R { private void M(string s) { System.ArgumentNullException.ThrowIfNull(s); System.Console.Write(1); } }");

    [Fact]
    public Task FEX0058_never_reports_a_lambda_or_a_local_function_in_a_CompilerGenerated_type() =>
        Silent<ParameterOnlyUsedForPreconditionCheckLocalAnalyzer>("[System.Runtime.CompilerServices.CompilerGenerated] public class R { public System.Action<string> F() => s => { System.ArgumentNullException.ThrowIfNull(s); }; public void G() { H(\"a\"); void H(string t) { System.ArgumentNullException.ThrowIfNull(t); System.Console.Write(1); } } }");
}
